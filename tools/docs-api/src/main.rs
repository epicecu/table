const GENERATED_NOTICE: &str = "<!-- Generated by table-docs-api. Do not edit manually. -->\n\n";

#[derive(Clone, Debug)]
struct ApiEntry {
    name: String,
    signature: String,
    docs: String,
}

fn main() -> Result<(), String> {
    let check = env::args().skip(1).any(|argument| argument == "--check");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let pages = generate_pages(&root)?;
    let output = root.join("docs/reference");
    if check {
        check_pages(&output, &pages)
    } else {
        write_pages(&output, &pages)
    }
}

fn generate_pages(root: &Path) -> Result<BTreeMap<String, String>, String> {
    let xml_root = root.join("build/docs/api/xml");
    let c_file = read_xml(&xml_root.join("table_8h.xml"))?;
    let cpp_curve = read_xml(&xml_root.join("classtable_1_1Curve.xml"))?;
    let cpp_map = read_xml(&xml_root.join("classtable_1_1Map.xml"))?;
    let cpp_namespace = read_xml(&xml_root.join("namespacetable.xml"))?;

    let c_functions = xml_entries(&c_file, "function");
    let mut pages = BTreeMap::new();
    pages.insert("c/index.md".into(), c_index());
    pages.insert("c/types.md".into(), render_c_types(&xml_root, &c_file)?);
    pages.insert(
        "c/initialisation.md".into(),
        render_entries(
            "C initialisation and validation",
            "Create validated borrowed views or mutable bindings before lookup.",
            "c",
            c_functions
                .iter()
                .filter(|entry| entry.name.ends_with("_init") || entry.name == "table_validate"),
        ),
    );
    pages.insert(
        "c/lookup.md".into(),
        render_entries(
            "C lookup and access",
            "Lookups clamp finite coordinates; accessors preserve the stored scalar type.",
            "c",
            c_functions
                .iter()
                .filter(|entry| entry.name.contains("lookup") || entry.name.contains("_get_")),
        ),
    );
    pages.insert(
        "c/mutation.md".into(),
        render_entries(
            "C mutation and replacement",
            "Mutations validate ordering and types. Whole-table replacement validates before copying.",
            "c",
            c_functions.iter().filter(|entry| {
                entry.name.contains("_set_") || entry.name == "table_replace"
            }),
        ),
    );

    pages.insert("cpp/index.md".into(), cpp_index());
    pages.insert(
        "cpp/status.md".into(),
        render_named_xml_entry("C++ Status", "cpp", &cpp_namespace, "enum", "Status")?,
    );
    pages.insert(
        "cpp/curve.md".into(),
        render_cpp_class("C++ Curve", &cpp_curve),
    );
    pages.insert("cpp/map.md".into(), render_cpp_class("C++ Map", &cpp_map));

    let rust = RustApi::load(root)?;
    pages.insert("rust/index.md".into(), rust_index());
    pages.insert(
        "rust/curve.md".into(),
        rust.render_type_page("Rust Curve", "Curve")?,
    );
    pages.insert(
        "rust/map.md".into(),
        rust.render_type_page("Rust Map", "Map")?,
    );
    pages.insert("rust/types.md".into(), rust.render_types_page()?);
    pages.insert("rust/protobuf.md".into(), rust.render_protobuf_page()?);
    pages.insert("rust/table-sys.md".into(), table_sys_page());
    Ok(pages)
}

fn read_xml(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|error| format!("failed to read {}: {error}", path.display()))
}

fn xml_entries(xml: &str, kind: &str) -> Vec<ApiEntry> {
    let document = Document::parse(xml).expect("Doxygen emitted valid XML");
    document
        .descendants()
        .filter(|node| {
            node.has_tag_name("memberdef")
                && node.attribute("kind") == Some(kind)
                && node.attribute("prot") == Some("public")
        })
        .filter_map(xml_entry)
        .collect()
}

fn xml_entry(node: Node<'_, '_>) -> Option<ApiEntry> {
    let name = child_text(node, "name");
    if name.is_empty() {
        return None;
    }
    let definition = child_text(node, "definition");
    let args = child_text(node, "argsstring");
    let signature = if node.attribute("kind") == Some("enum") {
        if node.attribute("strong") == Some("yes") {
            let qualified = child_text(node, "qualifiedname");
            format!("enum class {qualified}")
        } else {
            format!("typedef enum {name} {name}_t")
        }
    } else if definition.is_empty() {
        name.clone()
    } else {
        format!("{definition}{args}")
    };
    let brief = child(node, "briefdescription").map_or_else(String::new, node_text);
    let detail = child(node, "detaileddescription").map_or_else(String::new, node_text);
    let mut docs = match (brief.is_empty(), detail.is_empty()) {
        (false, false) => format!("{brief}\n\n{detail}"),
        (false, true) => brief,
        (true, false) => detail,
        (true, true) => String::new(),
    };
    let variants = node
        .children()
        .filter(|child| child.has_tag_name("enumvalue"))
        .map(|variant| child_text(variant, "name"))
        .filter(|name| !name.is_empty())
        .map(|name| format!("`{name}`"))
        .collect::<Vec<_>>();
    if !variants.is_empty() {
        if !docs.is_empty() {
            docs.push_str("\n\n");
        }
        write!(docs, "Values: {}.", variants.join(", ")).expect("writing to a String cannot fail");
    }
    Some(ApiEntry {
        name,
        signature: clean_space(&signature),
        docs,
    })
}

fn child<'a>(node: Node<'a, 'a>, name: &str) -> Option<Node<'a, 'a>> {
    node.children().find(|child| child.has_tag_name(name))
}

fn child_text(node: Node<'_, '_>, name: &str) -> String {
    child(node, name).map_or_else(String::new, node_text)
}

fn node_text(node: Node<'_, '_>) -> String {
    clean_space(
        &node
            .descendants()
            .filter(roxmltree::Node::is_text)
            .filter_map(|descendant| descendant.text())
            .collect::<Vec<_>>()
            .join(""),
    )
}

fn clean_space(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn render_entries<'a>(
    title: &str,
    introduction: &str,
    language: &str,
    entries: impl Iterator<Item = &'a ApiEntry>,
) -> String {
    let mut output = format!("{GENERATED_NOTICE}# {title}\n\n{introduction}\n\n");
    for entry in entries {
        write!(
            output,
            "## `{}`\n\n```{language}\n{};\n```\n\n{}\n\n",
            entry.name, entry.signature, entry.docs
        )
        .expect("writing to a String cannot fail");
    }
    output
}

fn render_c_types(xml_root: &Path, file_xml: &str) -> Result<String, String> {
    let document = Document::parse(file_xml).map_err(|error| error.to_string())?;
    let mut entries = xml_entries(file_xml, "enum");
    for inner in document
        .descendants()
        .filter(|node| node.has_tag_name("innerclass"))
    {
        let Some(reference) = inner.attribute("refid") else {
            continue;
        };
        let struct_xml = read_xml(&xml_root.join(format!("{reference}.xml")))?;
        let struct_document = Document::parse(&struct_xml).map_err(|error| error.to_string())?;
        let compound = struct_document
            .descendants()
            .find(|node| node.has_tag_name("compounddef"))
            .ok_or_else(|| format!("missing compound definition for {reference}"))?;
        let name = child_text(compound, "compoundname");
        let mut docs = child(compound, "briefdescription").map_or_else(String::new, node_text);
        let fields = xml_entries(&struct_xml, "variable")
            .into_iter()
            .map(|field| format!("`{}`", field.name))
            .collect::<Vec<_>>();
        if !fields.is_empty() {
            write!(docs, "\n\nFields: {}.", fields.join(", "))
                .expect("writing to a String cannot fail");
        }
        entries.push(ApiEntry {
            signature: format!("typedef struct {name} {name}_t"),
            name,
            docs,
        });
    }
    Ok(render_entries(
        "C types and status",
        "The C API uses explicit descriptors and scalar tags over caller-owned storage.",
        "c",
        entries.iter(),
    ))
}

fn render_named_xml_entry(
    title: &str,
    language: &str,
    xml: &str,
    kind: &str,
    name: &str,
) -> Result<String, String> {
    let entries = xml_entries(xml, kind);
    let entry = entries
        .iter()
        .find(|entry| entry.name == name)
        .ok_or_else(|| {
            let available = entries
                .iter()
                .map(|entry| entry.name.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            format!("Doxygen XML does not contain {name}; found: {available}")
        })?;
    Ok(render_entries(title, "", language, std::iter::once(entry)))
}

fn render_cpp_class(title: &str, xml: &str) -> String {
    let document = Document::parse(xml).expect("Doxygen emitted valid XML");
    let compound = document
        .descendants()
        .find(|node| node.has_tag_name("compounddef"))
        .expect("class XML contains a compound");
    let name = child_text(compound, "compoundname");
    let docs = child(compound, "briefdescription").map_or_else(String::new, node_text);
    let template = child(compound, "templateparamlist").map_or_else(String::new, |parameters| {
        parameters
            .children()
            .filter(|node| node.has_tag_name("param"))
            .map(|parameter| {
                let kind = child_text(parameter, "type");
                let name = child_text(parameter, "declname");
                let default = child_text(parameter, "defval");
                let mut value = if name.is_empty() {
                    kind
                } else {
                    format!("{kind} {name}")
                };
                if !default.is_empty() {
                    write!(value, " = {default}").expect("writing to a String cannot fail");
                }
                value
            })
            .collect::<Vec<_>>()
            .join(", ")
    });
    let methods = xml_entries(xml, "function");
    let mut output = format!(
        "{GENERATED_NOTICE}# {title}\n\n```cpp\ntemplate <{template}>\nclass {name}\n```\n\n{docs}\n\n"
    );
    for method in methods.iter().filter(|method| !method.docs.is_empty()) {
        write!(
            output,
            "## `{}`\n\n```cpp\n{}\n```\n\n{}\n\n",
            method.name, method.signature, method.docs
        )
        .expect("writing to a String cannot fail");
    }
    output
}

