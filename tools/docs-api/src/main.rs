#[derive(Default)]
struct RustApi {
    items: BTreeMap<String, RustItem>,
    methods: BTreeMap<String, Vec<ApiEntry>>,
}

#[derive(Clone, Default)]
struct RustItem {
    name: String,
    signature: String,
    docs: String,
    variants: Vec<ApiEntry>,
}

impl RustApi {
    fn load(root: &Path) -> Result<Self, String> {
        let mut api = Self::default();
        for relative in [
            "rust/table/src/lib.rs",
            "rust/table/src/scalar.rs",
            "rust/table/src/proto.rs",
        ] {
            let path = root.join(relative);
            let source = fs::read_to_string(&path)
                .map_err(|error| format!("failed to read {}: {error}", path.display()))?;
            let syntax = syn::parse_file(&source)
                .map_err(|error| format!("failed to parse {}: {error}", path.display()))?;
            api.collect(&syntax.items);
        }
        let generated_path = root.join("rust/table/src/generated/table.v1.rs");
        let generated_source = fs::read_to_string(&generated_path)
            .map_err(|error| format!("failed to read {}: {error}", generated_path.display()))?;
        let generated_syntax = syn::parse_file(&generated_source)
            .map_err(|error| format!("failed to parse {}: {error}", generated_path.display()))?;
        let mut messages = Self::default();
        messages.collect(&generated_syntax.items);
        let scalar_array = messages
            .items
            .remove("ScalarArray")
            .ok_or_else(|| "generated Prost API does not contain ScalarArray".to_owned())?;
        api.items.insert("MessageScalarArray".into(), scalar_array);
        Ok(api)
    }

    fn collect(&mut self, items: &[Item]) {
        for item in items {
            match item {
                Item::Struct(value) if is_public(&value.vis) && !doc_hidden(&value.attrs) => {
                    let name = value.ident.to_string();
                    self.items.insert(
                        name.clone(),
                        RustItem {
                            name,
                            signature: clean_tokens(&format!(
                                "pub struct {}{}",
                                value.ident,
                                value.generics.to_token_stream()
                            )),
                            docs: rust_docs(&value.attrs),
                            variants: Vec::new(),
                        },
                    );
                }
                Item::Enum(value) if is_public(&value.vis) && !doc_hidden(&value.attrs) => {
                    let name = value.ident.to_string();
                    let variants = value
                        .variants
                        .iter()
                        .map(|variant| ApiEntry {
                            name: variant.ident.to_string(),
                            signature: variant.to_token_stream().to_string(),
                            docs: rust_docs(&variant.attrs),
                        })
                        .collect();
                    self.items.insert(
                        name.clone(),
                        RustItem {
                            name: name.clone(),
                            signature: format!("pub enum {name}"),
                            docs: rust_docs(&value.attrs),
                            variants,
                        },
                    );
                }
                Item::Trait(value) if is_public(&value.vis) && !doc_hidden(&value.attrs) => {
                    let name = value.ident.to_string();
                    self.items.insert(
                        name.clone(),
                        RustItem {
                            name,
                            signature: clean_tokens(&format!(
                                "pub trait {}{}: {}",
                                value.ident,
                                value.generics.to_token_stream(),
                                value.supertraits.to_token_stream()
                            )),
                            docs: rust_docs(&value.attrs),
                            variants: Vec::new(),
                        },
                    );
                }
                Item::Impl(value) => {
                    let Some(name) = type_name(&value.self_ty) else {
                        continue;
                    };
                    for member in &value.items {
                        if let ImplItem::Fn(function) = member
                            && is_public(&function.vis)
                            && !doc_hidden(&function.attrs)
                        {
                            self.methods
                                .entry(name.clone())
                                .or_default()
                                .push(ApiEntry {
                                    name: function.sig.ident.to_string(),
                                    signature: clean_tokens(&format!(
                                        "pub {}",
                                        function.sig.to_token_stream()
                                    )),
                                    docs: rust_docs(&function.attrs),
                                });
                        }
                    }
                }
                Item::Mod(module) if is_public(&module.vis) => {
                    if let Some((_, nested)) = &module.content {
                        self.collect(nested);
                    }
                }
                _ => {}
            }
        }
    }

    fn render_type_page(&self, title: &str, name: &str) -> Result<String, String> {
        let item = self
            .items
            .get(name)
            .ok_or_else(|| format!("Rust API does not contain {name}"))?;
        let mut output = format!(
            "{GENERATED_NOTICE}# {title}\n\n```rust\n{}\n```\n\n{}\n\n",
            item.signature, item.docs
        );
        for method in self.methods.get(name).into_iter().flatten() {
            write!(
                output,
                "## `{}`\n\n```rust\n{}\n```\n\n{}\n\n",
                method.name, method.signature, method.docs
            )
            .expect("writing to a String cannot fail");
        }
        Ok(output)
    }

    fn render_types_page(&self) -> Result<String, String> {
        let mut output = format!(
            "{GENERATED_NOTICE}# Rust errors and scalar types\n\nThe safe crate exposes explicit error and scalar representations.\n\n"
        );
        for name in ["Error", "Scalar", "ScalarType"] {
            output.push_str(&self.render_item(name)?);
        }
        Ok(output)
    }

    fn render_protobuf_page(&self) -> Result<String, String> {
        let mut output = format!(
            "{GENERATED_NOTICE}# Rust Protobuf snapshots\n\nEnable the `prost` feature to use stable `table.v1` messages and validated conversions. `Curve` and `Map` implement conversions to and from their corresponding messages.\n\n"
        );
        for name in ["SnapshotError", "MessageScalarArray"] {
            output.push_str(&self.render_item(name)?);
        }
        output.push_str("## Messages\n\nThe generated `table::proto::v1` module contains `ScalarArray`, `Curve`, `Map`, and `ScalarType`.\n");
        Ok(output)
    }

    fn render_item(&self, name: &str) -> Result<String, String> {
        let item = self
            .items
            .get(name)
            .ok_or_else(|| format!("Rust API does not contain {name}"))?;
        let mut output = format!(
            "## `{}`\n\n```rust\n{}\n```\n\n{}\n\n",
            item.name, item.signature, item.docs
        );
        if !item.variants.is_empty() {
            output.push_str("| Variant | Meaning |\n| --- | --- |\n");
            for variant in &item.variants {
                writeln!(output, "| `{}` | {} |", variant.name, variant.docs)
                    .expect("writing to a String cannot fail");
            }
            output.push('\n');
        }
        Ok(output)
    }
}

fn is_public(visibility: &Visibility) -> bool {
    matches!(visibility, Visibility::Public(_))
}

fn doc_hidden(attributes: &[Attribute]) -> bool {
    attributes.iter().any(|attribute| {
        attribute.path().is_ident("doc")
            && attribute
                .meta
                .to_token_stream()
                .to_string()
                .contains("hidden")
    })
}

fn rust_docs(attributes: &[Attribute]) -> String {
    let mut lines = Vec::new();
    for attribute in attributes {
        if !attribute.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(value) = &attribute.meta
            && let syn::Expr::Lit(expression) = &value.value
            && let syn::Lit::Str(text) = &expression.lit
        {
            lines.push(text.value().trim().to_owned());
        }
    }
    lines.join("\n").replace("[`", "`").replace("`]", "`")
}

fn type_name(value: &syn::Type) -> Option<String> {
    if let syn::Type::Path(path) = value {
        path.path
            .segments
            .last()
            .map(|segment| segment.ident.to_string())
    } else {
        None
    }
}

fn clean_tokens(value: &str) -> String {
    value
        .replace(" < ", "<")
        .replace("< ", "<")
        .replace(" >", ">")
        .replace(" :: ", "::")
        .replace(" ,", ",")
        .replace(" : ", ": ")
        .replace(" (& ", "(&")
        .replace(" (& mut ", "(&mut ")
        .replace("& mut ", "&mut ")
        .replace("& self", "&self")
        .replace("& [", "&[")
        .replace(" (", "(")
        .replace("[ ", "[")
        .replace(" ]", "]")
}

fn expected_files(pages: &BTreeMap<String, String>) -> BTreeSet<PathBuf> {
    pages.keys().map(PathBuf::from).collect()
}

fn check_pages(output: &Path, pages: &BTreeMap<String, String>) -> Result<(), String> {
    for (relative, expected) in pages {
        let path = output.join(relative);
        let actual = fs::read_to_string(&path)
            .map_err(|_| format!("{} is missing; run task docs:api", path.display()))?;
        if &actual != expected {
            return Err(format!("{} is stale; run task docs:api", path.display()));
        }
    }
    let expected = expected_files(pages);
    let mut existing = BTreeSet::new();
    collect_markdown(output, output, &mut existing)?;
    if existing != expected {
        return Err("generated API file set is stale; run task docs:api".into());
    }
    Ok(())
}

fn write_pages(output: &Path, pages: &BTreeMap<String, String>) -> Result<(), String> {
    if output.exists() {
        fs::remove_dir_all(output)
            .map_err(|error| format!("failed to clear {}: {error}", output.display()))?;
    }
    for (relative, content) in pages {
        let path = output.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| format!("failed to create {}: {error}", parent.display()))?;
        }
        fs::write(&path, content)
            .map_err(|error| format!("failed to write {}: {error}", path.display()))?;
    }
    println!("Generated {} API reference pages", pages.len());
    Ok(())
}

fn collect_markdown(
    root: &Path,
    current: &Path,
    files: &mut BTreeSet<PathBuf>,
) -> Result<(), String> {
    if !current.exists() {
        return Ok(());
    }
    for entry in fs::read_dir(current).map_err(|error| error.to_string())? {
        let path = entry.map_err(|error| error.to_string())?.path();
        if path.is_dir() {
            collect_markdown(root, &path, files)?;
        } else if path.extension().is_some_and(|extension| extension == "md") {
            files.insert(
                path.strip_prefix(root)
                    .map_err(|error| error.to_string())?
                    .to_owned(),
            );
        }
    }
    Ok(())
}

